        -not (Test-Path -LiteralPath $packageBackup -PathType Leaf)) {
    New-Item -ItemType Directory -Path $packageBackupDirectory -Force | Out-Null
    Copy-Item -LiteralPath $pinmameArchive -Destination $packageBackup
