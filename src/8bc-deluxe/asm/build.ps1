function Write-ChecksumInclude([byte]$Value) {
    @(
        '; Generated by build.ps1; do not edit.'
        ('ROM_ADDITIVE_CHECKSUM_COMPENSATION_VALUE equ $' + $Value.ToString('X2'))
    ) | Set-Content -LiteralPath $checksumInclude -Encoding ascii
}

function Invoke-DasmBuild {
    Push-Location $asmDirectory
    try {
        & $assembler 'main.asm' '-f3' "-o$rebuiltRom" "-l$listing" "-s$symbols" '-T1' '-R'
        if ($LASTEXITCODE -ne 0) {
            throw "DASM failed with exit code $LASTEXITCODE"
        }
    }
    finally {
        Pop-Location
    }
}

function Get-AdditiveChecksum([byte[]]$Bytes) {
    $sum = 0
    foreach ($value in $Bytes) {
        $sum = ($sum + $value) -band 0xFF
    }
    return $sum
}

Write-ChecksumInclude 0
Invoke-DasmBuild
$firstPassBytes = [System.IO.File]::ReadAllBytes($rebuiltRom)
if ($firstPassBytes.Length -ne 16384) {
    throw "First-pass ROM is $($firstPassBytes.Length) bytes; expected 16384."
}
$firstPassSum = Get-AdditiveChecksum $firstPassBytes
$checksumCompensation = ($firstPassBytes[0] + (0xFF - $firstPassSum)) -band 0xFF

Write-ChecksumInclude ([byte]$checksumCompensation)
Invoke-DasmBuild
$rebuiltBytes = [System.IO.File]::ReadAllBytes($rebuiltRom)
$originalBytes = [System.IO.File]::ReadAllBytes($originalRom)
if ($rebuiltBytes.Length -ne 16384) {
    throw "Rebuilt ROM is $($rebuiltBytes.Length) bytes; expected 16384."
}
$startupChecksum = Get-AdditiveChecksum $rebuiltBytes
if ($rebuiltBytes[0] -ne $checksumCompensation -or $startupChecksum -ne 0xFF) {
    throw "Startup checksum finalization failed: C000 is $('$' + $rebuiltBytes[0].ToString('X2')), sum is $('$' + $startupChecksum.ToString('X2'))."
}

function Get-DasmSymbolAddress([string]$Name) {
    $escapedName = [regex]::Escape($Name)
    $symbolLine = Select-String -LiteralPath $symbols -Pattern ('^' + $escapedName + '\s+([0-9A-Fa-f]+)\s') | Select-Object -First 1
    if (-not $symbolLine) {
        throw "Required DASM symbol '$Name' is missing from $symbols."
    }
    return [Convert]::ToInt32($symbolLine.Matches[0].Groups[1].Value, 16)
}

# The canonical selector at C5C3 advances X by 7 bytes through F821 and then
# by 6 more through F822, giving each player a 13-byte slot. Four slots begin
# at 10C7 and end at 10FA. Deluxe must begin at the very next byte; this check
# prevents a future RAM-layout edit from silently corrupting Player 4 again.
$canonicalPlayerRecordStart = 0x10C7
$canonicalPlayerRecordStride = 13
$canonicalPlayerRecordCount = 4
$canonicalPlayerRecordEnd = $canonicalPlayerRecordStart +
    ($canonicalPlayerRecordStride * $canonicalPlayerRecordCount) - 1
$deluxeRamStart = Get-DasmSymbolAddress 'DELUXE_COLLECT_STATE'
$deluxeRamEnd = Get-DasmSymbolAddress 'DELUXE_HOLE_NEXT_BONUS_MULTIPLIER'
if ($deluxeRamStart -ne ($canonicalPlayerRecordEnd + 1)) {
    throw "Deluxe RAM must begin at $('$' + ($canonicalPlayerRecordEnd + 1).ToString('X4')) immediately after the four canonical player slots; found $('$' + $deluxeRamStart.ToString('X4'))."
}
if ($deluxeRamStart -le $canonicalPlayerRecordEnd -or $deluxeRamEnd -gt 0x17FF) {
    throw "Deluxe RAM range $('$' + $deluxeRamStart.ToString('X4'))-$('$' + $deluxeRamEnd.ToString('X4')) overlaps canonical player records or exceeds U4 RAM."
}

